// Deep Bounce: replaces the stock template activity (copied in by tools/android/build_release.sh).
// The stock version calls Godot.enableImmersiveMode(..., true) / enableEdgeToEdge(..., true) on every resume,
// which run Window#setDecorFitsSystemWindows (deprecated on Android 15) and show the system bars again, plus
// androidx EdgeToEdge.enable(), which sets the deprecated status/navigation bar colours. Android 15+ already
// draws apps edge to edge, so here the bars are only hidden through WindowInsetsControllerCompat; the game
// keeps its buttons inside the safe area reported by the DeepBouncePlay plugin.

package com.godot.game;

import org.godotengine.godot.Godot;
import org.godotengine.godot.GodotActivity;

import android.os.Bundle;
import android.util.Log;
import android.view.Window;

import androidx.core.splashscreen.SplashScreen;
import androidx.core.view.WindowCompat;
import androidx.core.view.WindowInsetsCompat;
import androidx.core.view.WindowInsetsControllerCompat;

public class GodotApp extends GodotActivity {
	static {
		// .NET libraries.
		if (BuildConfig.FLAVOR.equals("mono")) {
			try {
				Log.v("GODOT", "Loading System.Security.Cryptography.Native.Android library");
				System.loadLibrary("System.Security.Cryptography.Native.Android");
			} catch (UnsatisfiedLinkError e) {
				Log.e("GODOT", "Unable to load System.Security.Cryptography.Native.Android library");
			}
		}
	}

	private final Runnable updateWindowAppearance = () -> {
		Window window = getWindow();
		if (window == null) {
			return;
		}
		WindowInsetsControllerCompat controller = WindowCompat.getInsetsController(window, window.getDecorView());
		controller.setSystemBarsBehavior(WindowInsetsControllerCompat.BEHAVIOR_SHOW_TRANSIENT_BARS_BY_SWIPE);
		controller.hide(WindowInsetsCompat.Type.systemBars());
		Godot godot = getGodot();
		if (godot != null) {
			godot.setSystemBarsAppearance();
		}
	};

	@Override
	public void onCreate(Bundle savedInstanceState) {
		SplashScreen.installSplashScreen(this);
		super.onCreate(savedInstanceState);
	}

	@Override
	public void onResume() {
		super.onResume();
		updateWindowAppearance.run();
	}

	@Override
	public void onWindowFocusChanged(boolean hasFocus) {
		super.onWindowFocusChanged(hasFocus);
		if (hasFocus) {
			updateWindowAppearance.run();
		}
	}

	@Override
	public void onGodotMainLoopStarted() {
		super.onGodotMainLoopStarted();
		runOnUiThread(updateWindowAppearance);
	}
}
